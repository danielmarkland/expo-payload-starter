import { describe, expect, it } from 'vitest'
import { encodeSiteArchive, decodeSiteArchive, sha256 } from './siteTransfer.js'
import { validateSiteArchive } from './siteTransfer/payload.js'
import { projectState } from './siteTransfer/fields.js'
import type { SiteTransferManifest } from '@danielmarkland/publishing-contracts/siteTransfer'
const bytes = Buffer.from('original media')
const hash = sha256(bytes)
const manifest: SiteTransferManifest = {
  format: 'publishing-site',
  version: 1,
  createdAt: '2026-10-05T00:00:00.000Z',
  extensions: {},
  resources: ['media'],
  records: [
    {
      key: 'm',
      resource: 'media',
      draft: false,
      asset: 'm',
      current: { data: { alt: 'Logo' }, references: [] },
    },
  ],
  assets: [
    {
      key: 'm',
      path: `assets/${hash}`,
      sha256: hash,
      size: bytes.length,
      filename: 'logo.png',
      mimeType: 'image/png',
    },
  ],
}
const encode = () =>
  encodeSiteArchive({ manifest, assets: new Map([[`assets/${hash}`, bytes]]) })
describe('portable site archive', () => {
  it('preserves paragraph formatting generated by the Payload editor', () => {
    const content = {
      root: {
        type: 'root',
        version: 1,
        children: [
          {
            type: 'paragraph',
            version: 1,
            textFormat: 1,
            textStyle: 'color: red;',
            children: [
              { type: 'text', version: 1, text: 'Collection', format: 1 },
            ],
          },
        ],
      },
    }
    expect(
      projectState(
        { content },
        [{ name: 'content', type: 'richText' }],
        () => '',
      ),
    ).toEqual({
      data: { content },
      references: [],
    })
    expect(() =>
      projectState(
        { content: { root: { type: 'root', unexpected: true } } },
        [{ name: 'content', type: 'richText' }],
        () => '',
      ),
    ).toThrow('Unsupported rich text property unexpected')
  })
  it('round trips originals and metadata', () => {
    const result = decodeSiteArchive(encode())
    expect(result.manifest).toEqual(manifest)
    expect(result.assets.get(`assets/${hash}`)).toEqual(bytes)
  })
  it('rejects corrupt media, versions, truncated archives and traversal paths', () => {
    const corrupt = encode()
    corrupt[1024 + 512] ^= 1
    expect(() => decodeSiteArchive(corrupt)).toThrow()
    expect(() => decodeSiteArchive(encode().subarray(0, -512))).toThrow()
    const unsafe = encode()
    unsafe.write('../secret', 0)
    expect(() => decodeSiteArchive(unsafe)).toThrow('path')
    expect(() =>
      encodeSiteArchive({
        manifest: {
          ...manifest,
          version: 2,
        } as unknown as SiteTransferManifest,
        assets: new Map(),
      }),
    ).toThrow()
  })
  it('projects only declared fields and remaps nested relationships', () => {
    const state = projectState(
      {
        title: 'Page',
        internalOwner: 'private',
        password: 'secret',
        rows: [{ id: 'row', image: 12 }],
      },
      [
        { name: 'title', type: 'text' },
        {
          name: 'rows',
          type: 'array',
          fields: [{ name: 'image', type: 'upload', relationTo: 'media' }],
        },
      ],
      (slug, id) => `${slug}:${id}`,
    )
    expect(state).toEqual({
      data: { title: 'Page', rows: [{ image: null }] },
      references: [{ path: ['rows', 0, 'image'], target: 'media:12' }],
    })
  })
  it('rejects unknown blocks, dangling references and prototype properties', () => {
    expect(() =>
      projectState(
        { layout: [{ blockType: 'missing' }] },
        [{ name: 'layout', type: 'blocks', blocks: [] }],
        () => '',
      ),
    ).toThrow('Unsupported block')
    expect(() =>
      projectState(JSON.parse('{"__proto__":{}}'), [], () => ''),
    ).toThrow('Unsafe')
  })
})

it('accepts presentation field reordering without allowing undeclared fields', () => {
  const state = {
    data: { title: 'Example', links: ['first', 'second'] },
    references: [],
  }
  const archive = {
    manifest: {
      format: 'publishing-site',
      version: 1,
      createdAt: '2026-10-05T00:00:00.000Z',
      extensions: {},
      resources: ['pages'],
      records: [{ key: 'p', resource: 'pages', draft: false, current: state }],
      assets: [],
    },
    assets: new Map(),
  }
  const options = {
    resources: [
      {
        key: 'pages',
        slug: 'pages',
        kind: 'collection',
        fields: [
          { name: 'links', type: 'json' },
          { name: 'title', type: 'text' },
        ],
      },
    ],
  } as const
  const bytes = encodeSiteArchive(
    archive as Parameters<typeof encodeSiteArchive>[0],
  )
  expect(() =>
    validateSiteArchive(
      bytes,
      options as unknown as Parameters<typeof validateSiteArchive>[1],
    ),
  ).not.toThrow()
  const invalid = structuredClone(archive)
  invalid.manifest.records[0].current.data = {
    ...state.data,
    secret: 'not allowed',
  } as typeof state.data
  expect(() =>
    validateSiteArchive(
      encodeSiteArchive(invalid as Parameters<typeof encodeSiteArchive>[0]),
      options as unknown as Parameters<typeof validateSiteArchive>[1],
    ),
  ).toThrow('Unsupported field secret')
})
